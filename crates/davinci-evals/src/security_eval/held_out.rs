#[cfg(test)]
mod tests {
    use super::super::corpus::FAMILIES;
    use super::*;

    #[test]
    fn security_eval_held_out_corpus_validates_and_keeps_labels_out_of_worker_files() {
        let (corpus, sources) = corpus();
        let validated = corpus
            .validate(&sources)
            .expect("held-out corpus must validate");
        assert_eq!(validated.summary().pairs, 40);
        assert_eq!(validated.summary().cases, 80);
        assert!(validated.summary().cross_file_vulnerable_cases >= 10);
        assert!(FAMILIES
            .iter()
            .all(|family| validated.summary().pairs_by_family[family] >= 4));
        let worker = serde_json::to_string(
            validated
                .worker_files(&corpus.pairs[0].vulnerable.id)
                .unwrap(),
        )
        .unwrap();
        assert!(!worker.contains("owner predicate on document lookup"));
        assert!(!worker.contains(&corpus.pairs[0].id));
        assert!(!worker.contains("secure_control_rationale"));
    }
}
