struct Draft {
    family: Family,
    slug: &'static str,
    actor: &'static str,
    control: &'static str,
    boundary: &'static str,
    sink: &'static str,
    occurrence: &'static str,
    rationale: &'static str,
    min: Severity,
    max: Severity,
    vuln_handler: &'static str,
    vuln_routes: &'static str,
    secure_handler: &'static str,
    secure_routes: &'static str,
}

pub fn corpus() -> (Corpus, SourceCases) {
    let mut sources = SourceCases::new();
    let pairs = drafts()
        .into_iter()
        .map(|draft| materialize(draft, &mut sources))
        .collect();
    (
        Corpus {
            schema_version: 1,
            id: "held-out-security-2026-09".into(),
            pairs,
        },
        sources,
    )
}

fn materialize(draft: Draft, sources: &mut SourceCases) -> Pair {
    let pair_id = draft.slug.to_string();
    let vulnerable = materialize_case(
        format!("{pair_id}-v"),
        draft.vuln_handler,
        draft.vuln_routes,
        sources,
    );
    let secure = materialize_case(
        format!("{pair_id}-s"),
        draft.secure_handler,
        draft.secure_routes,
        sources,
    );
    Pair {
        id: pair_id,
        family: draft.family,
        vulnerable,
        secure,
        expected: ExpectedFinding {
            identity: CausalIdentity {
                control: draft.control.into(),
                trust_boundary: draft.boundary.into(),
                sink: draft.sink.into(),
                occurrence: draft.occurrence.into(),
            },
            actor: draft.actor.into(),
            preconditions: vec!["reachable handler in the scanned snapshot".into()],
            classification: Classification::Confirmed,
            minimum_severity: draft.min,
            maximum_severity: draft.max,
        },
        secure_control_rationale: draft.rationale.into(),
    }
}

fn materialize_case(id: String, handler: &str, routes: &str, sources: &mut SourceCases) -> Case {
    let files: BTreeMap<_, _> = [
        ("handler.rs".into(), handler.to_string()),
        ("routes.rs".into(), routes.to_string()),
    ]
    .into();
    let hashes = files
        .iter()
        .map(|(path, text): (&String, &String)| {
            (
                path.clone(),
                format!("{:x}", Sha256::digest(text.as_bytes())),
            )
        })
        .collect();
    let handler_end = handler.lines().count().max(1);
    let routes_end = routes.lines().count().max(1);
    sources.insert(id.clone(), files);
    Case {
        id,
        files: hashes,
        decisive_evidence: vec![
            Anchor {
                path: "handler.rs".into(),
                start_line: 1,
                end_line: handler_end,
                role: EvidenceRole::Control,
            },
            Anchor {
                path: "routes.rs".into(),
                start_line: 1,
                end_line: routes_end,
                role: EvidenceRole::Sink,
            },
        ],
    }
}

