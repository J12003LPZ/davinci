#!/usr/bin/env python3
"""P19: the DaVinci comparison report.

Reads the coverage ledger and the per-row results, and writes `results.md` in
the evidence folder. Every row is shown as DaVinci has it: state, result and the
recorded owner/limitation. `--run` first runs the suite that covers every kept
golden and every adverse test (the test IDs are the coverage ids), so the report
is written from a fresh result set.

Usage:
    python scripts/ui/cc2316_report.py [--run]
        [--evidence C:/Users/sergi/Desktop/davinci-cc2316-evidence]
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DEFAULT_EVIDENCE = Path("C:/Users/sergi/Desktop/davinci-cc2316-evidence")


def run_suite() -> tuple[int, dict | None, str]:
    """Run the coverage test IDs against DaVinci through the P19 adapter."""
    suite_path = DEFAULT_EVIDENCE / "suite.json"
    completed = subprocess.run(
        [sys.executable, str(REPO / "scripts" / "ui" / "run_suite.py"),
         "--out", str(suite_path)],
        cwd=REPO, capture_output=True, text=True)
    tail = "\n".join((completed.stderr or completed.stdout).splitlines()[-6:])
    data = None
    if suite_path.is_file():
        data = json.loads(suite_path.read_text(encoding="utf-8"))
    return completed.returncode, data, tail


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--evidence", type=Path, default=DEFAULT_EVIDENCE)
    parser.add_argument("--run", action="store_true", help="run the full suite first")
    parser.add_argument("--out", type=Path)
    args = parser.parse_args(argv)

    suite = ""
    suite_data = None
    if args.run:
        code, suite_data, tail = run_suite()
        suite = f"Suite exit {code}. Last lines:\n\n```\n{tail}\n```\n\n"
    elif (args.evidence / "suite.json").is_file():
        suite_data = json.loads((args.evidence / "suite.json").read_text(encoding="utf-8"))

    coverage = json.loads((args.evidence / "coverage.json").read_text(encoding="utf-8"))
    results = json.loads((args.evidence / "results.json").read_text(encoding="utf-8"))
    rows = coverage.get("rows") or []
    by_kind = Counter(row["kind"] for row in rows)
    by_state = Counter(row.get("state", "?") for row in rows)
    weak = [row for row in rows if row.get("state") in
            ("NOT_STARTED", "UNCLASSIFIED", "FAILED", "BLOCKED")]
    partial = [row for row in rows if row.get("state") == "IN_PROGRESS"]
    verified = [row for row in rows if row.get("state") == "VERIFIED"]

    lines = [
        "# DaVinci TUI parity: results",
        "",
        "Generated by `scripts/ui/cc2316_report.py` from `coverage.json` and "
        "`results.json`. This is the DaVinci result only; the reference's own "
        "outcome is not restated. Rows that are not at zero differences carry "
        "their owner and limitation.",
        "",
        f"Rows: {len(rows)} " + ", ".join(f"{kind} {count}" for kind, count in sorted(by_kind.items())),
        "",
        "| State | Rows |",
        "|---|---:|",
        *[f"| {state} | {count} |" for state, count in sorted(by_state.items())],
        "",
        f"VERIFIED at zero differences: {len(verified)}. "
        f"IN_PROGRESS with a recorded limitation: {len(partial)}. "
        f"Not started, unclassified, failed or blocked: {len(weak)}.",
        "",
        "## Goldens",
        "",
        "| Golden | Reference | Tier | State | Result | Limitation |",
        "|---|---|---|---|---|---|",
    ]
    for row in sorted((r for r in rows if r["kind"] == "golden"), key=lambda r: r["id"]):
        result = results.get(row["id"], {})
        limitation = str(result.get("limitation") or "").replace("|", "\\|")
        lines.append(
            f"| {row['id']} | {row.get('reference_status', '')} | {row.get('tier', '')} | "
            f"{row.get('state', '')} | {result.get('result', '')} | {limitation} |"
        )

    lines += ["", "## Features and commands", ""]
    for kind in ("feature", "command", "keybinding"):
        group = [r for r in rows if r["kind"] == kind]
        if not group:
            continue
        lines += [
            f"### {kind.capitalize()} ({len(group)})",
            "",
            "| Id | Label | Reference | State | Limitation |",
            "|---|---|---|---|---|",
        ]
        for row in sorted(group, key=lambda r: r["id"]):
            result = results.get(row["id"], {})
            limitation = str(result.get("limitation") or "").replace("|", "\\|")
            label = str(row.get("label") or "").replace("|", "\\|")
            lines.append(
                f"| {row['id']} | {label} | {row.get('reference_status', '')} | "
                f"{row.get('state', '')} | {limitation} |"
            )
        lines.append("")

    lines += [
        "## Not verified / blocked / NO_REFERENCE",
        "",
        "These are shown as they are, not folded into a pass:",
        "",
    ]
    for row in weak:
        result = results.get(row["id"], {})
        limitation = str(result.get("limitation") or "").replace("\n", " ")
        lines.append(f"- `{row['id']}` ({row['kind']}, {row.get('state', '')}): {limitation}")
    if not weak:
        lines.append("None.")
    if suite_data:
        failed = [record for record in suite_data.get("records", [])
                  if record.get("outcome") in ("failed", "error", "unexpected_success")]
        lines += [
            "## Suite",
            "",
            f"{suite_data.get('tests', 0)} tests: "
            f"{suite_data.get('failures', 0)} failures, "
            f"{suite_data.get('errors', 0)} errors, "
            f"{suite_data.get('skipped', 0)} skipped, "
            f"{suite_data.get('expected_failures', 0)} expected failures.",
            "",
        ]
        if failed:
            lines += ["| Test | Outcome | Detail |", "|---|---|---|"]
            for record in failed:
                detail = str(record.get("detail") or "").strip().splitlines()
                detail = detail[-1] if detail else ""
                lines.append(
                    f"| `{record['id']}` | {record['outcome']} | "
                    f"{detail.replace('|', chr(92) + '|')} |"
                )
        else:
            lines.append("Every selected test passed.")
        lines.append("")
    lines += ["## Run", "", suite or "Not run in this invocation (`--run` was not passed).", ""]

    out = args.out or (args.evidence / "results.md")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", out, "rows", len(rows))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
